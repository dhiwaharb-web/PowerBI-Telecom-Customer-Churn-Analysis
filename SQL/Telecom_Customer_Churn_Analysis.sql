-- TELECOM CUSTOMER CHURN ANALYSIS

CREATE DATABASE telecom_churn_analysis;
USE telecom_churn_analysis;


-- 1. DATA PREVIEW
-- Q1. What does the cleaned telecom customer dataset look like?

SELECT * FROM telecom_data LIMIT 10;


-- 2. OVERALL CUSTOMER ANALYSIS
-- Q2. How many total customers are present in the dataset?

SELECT COUNT(*) AS Total_Customers
    FROM telecom_data;


-- Q3. How many customers have churned?

SELECT COUNT(*) AS Churned_Customers
    FROM telecom_data
    WHERE `Customer Status` = 'Churned';


-- Q4. What is the overall churn rate?

SELECT ROUND(
    SUM(CASE WHEN `Customer Status` = 'Churned' THEN 1 ELSE 0 END)
    * 100.0 / COUNT(*), 2
) AS Churn_Rate
    FROM telecom_data;


-- 3. CONTRACT ANALYSIS
-- Q5. Which contract type has the highest churn rate?

SELECT `Contract`,
    COUNT(*) AS Total_Customers,
    SUM(CASE WHEN `Customer Status` = 'Churned' THEN 1 ELSE 0 END)
        AS Churned_Customers,
    ROUND(
        SUM(CASE WHEN `Customer Status` = 'Churned' THEN 1 ELSE 0 END)
        * 100.0 / COUNT(*), 2
    ) AS Churn_Rate
    FROM telecom_data
    GROUP BY `Contract`
    ORDER BY Churn_Rate DESC;


-- Q6. How many churned customers are there for each contract type?

SELECT `Contract`,
    COUNT(*) AS Churned_Customers
    FROM telecom_data
    WHERE `Customer Status` = 'Churned'
    GROUP BY `Contract`
    ORDER BY Churned_Customers DESC;


-- 4. INTERNET SERVICE ANALYSIS
-- Q7. How does churn rate differ between customers
--     with and without internet service?

SELECT `Internet Service`,
    COUNT(*) AS Total_Customers,
    SUM(CASE WHEN `Customer Status` = 'Churned' THEN 1 ELSE 0 END)
        AS Churned_Customers,
    ROUND(
        SUM(CASE WHEN `Customer Status` = 'Churned' THEN 1 ELSE 0 END)
        * 100.0 / COUNT(*), 2
    ) AS Churn_Rate
    FROM telecom_data
    GROUP BY `Internet Service`
    ORDER BY Churn_Rate DESC;


-- Q8. Which internet type has the highest churn rate?

SELECT `Internet Type`,
    COUNT(*) AS Total_Customers,
    SUM(CASE WHEN `Customer Status` = 'Churned' THEN 1 ELSE 0 END)
        AS Churned_Customers,
    ROUND(
        SUM(CASE WHEN `Customer Status` = 'Churned' THEN 1 ELSE 0 END)
        * 100.0 / COUNT(*), 2
    ) AS Churn_Rate
    FROM telecom_data
    WHERE `Internet Type` IS NOT NULL
    GROUP BY `Internet Type`
    ORDER BY Churn_Rate DESC;


-- 5. TENURE ANALYSIS
-- Q9. Which tenure group has the highest churn rate?

SELECT `Tenure Group`,
    COUNT(*) AS Total_Customers,
