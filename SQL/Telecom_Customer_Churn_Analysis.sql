-- 13. BUSINESS ANALYSIS
-- Q24. Which internet type generates the highest churned revenue?

SELECT `Internet Type`,
    COUNT(*) AS Churned_Customers,
    ROUND(SUM(`Total Revenue`), 2) AS Churned_Revenue
    FROM telecom_data
    WHERE `Customer Status` = 'Churned'
    AND `Internet Type` IS NOT NULL
    GROUP BY `Internet Type`
    ORDER BY Churned_Revenue DESC;


-- Q25. Which contract type generates the highest churned revenue?

