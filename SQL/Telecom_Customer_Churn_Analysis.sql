-- 14. ADVANCED SQL
-- Q26. How can customers be ranked based on total revenue?

SELECT `Customer ID`,
    ROUND(`Total Revenue`, 2) AS Customer_Revenue,
    RANK() OVER (
        ORDER BY `Total Revenue` DESC
    ) AS Revenue_Rank
    FROM telecom_data
    LIMIT 10;


-- Q27. How can churned customers be ranked based on total revenue?

SELECT `Customer ID`,
    ROUND(`Total Revenue`, 2) AS Customer_Revenue,
    RANK() OVER (
        ORDER BY `Total Revenue` DESC
    ) AS Revenue_Rank
    FROM telecom_data
    WHERE `Customer Status` = 'Churned'
    LIMIT 10;