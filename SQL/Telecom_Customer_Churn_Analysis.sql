-- 8. REVENUE ANALYSIS
-- Q14. What is the total revenue generated by all customers?

SELECT ROUND(SUM(`Total Revenue`), 2) AS Total_Revenue
    FROM telecom_data;


-- Q15. How much revenue was generated by churned customers?

SELECT ROUND(SUM(`Total Revenue`), 2) AS Churned_Revenue
    FROM telecom_data
    WHERE `Customer Status` = 'Churned';


-- Q16. What percentage of total revenue comes from churned customers?

SELECT ROUND(
    SUM(CASE
        WHEN `Customer Status` = 'Churned'
        THEN `Total Revenue`
        ELSE 0
    END) * 100.0 / SUM(`Total Revenue`), 2
) AS Churned_Revenue_Share
    FROM telecom_data;


-- Q17. What is the average monthly charge for churned
--     and retained customers?

SELECT `Customer Status`,
    ROUND(AVG(`Monthly Charge`), 2) AS Average_Monthly_Charge
    FROM telecom_data
    GROUP BY `Customer Status`;


-- 9. CUSTOMER VALUE ANALYSIS
-- Q18. Who are the top 10 customers based on total revenue?

SELECT `Customer ID`,
    ROUND(`Total Revenue`, 2) AS Total_Revenue
    FROM telecom_data
    ORDER BY `Total Revenue` DESC
    LIMIT 10;


-- Q19. Which high-value customers have churned?

SELECT `Customer ID`,
    ROUND(`Total Revenue`, 2) AS Total_Revenue,
    `Contract`,
    `Tenure in Months`,
    `Customer Status`
    FROM telecom_data
    WHERE `Customer Status` = 'Churned'
    ORDER BY `Total Revenue` DESC
    LIMIT 10;


-- 10. CHURN CATEGORY ANALYSIS
-- Q20. Which churn category contributes the most churned customers?

SELECT `Churn Category`,
    COUNT(*) AS Churned_Customers
    FROM telecom_data
    WHERE `Customer Status` = 'Churned'
    AND `Churn Category` IS NOT NULL
    GROUP BY `Churn Category`
    ORDER BY Churned_Customers DESC;


-- 11. CHURN REASON ANALYSIS
-- Q21. What are the top 10 reasons customers churn?

SELECT `Churn Reason`,
    COUNT(*) AS Churned_Customers
    FROM telecom_data
    WHERE `Customer Status` = 'Churned'
    AND `Churn Reason` IS NOT NULL
    GROUP BY `Churn Reason`
    ORDER BY Churned_Customers DESC
    LIMIT 10;


-- Q22. Which churn reasons are associated with the highest revenue loss?

SELECT `Churn Reason`,
    COUNT(*) AS Churned_Customers,
    ROUND(SUM(`Total Revenue`), 2) AS Revenue_Lost
    FROM telecom_data
    WHERE `Customer Status` = 'Churned'
    AND `Churn Reason` IS NOT NULL
    GROUP BY `Churn Reason`
    ORDER BY Revenue_Lost DESC
    LIMIT 10;


