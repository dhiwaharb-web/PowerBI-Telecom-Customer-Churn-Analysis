    ORDER BY Churn_Rate DESC;


-- Q10. What is the average tenure of churned and retained customers?

SELECT `Customer Status`,
    ROUND(AVG(`Tenure in Months`), 2) AS Average_Tenure
    FROM telecom_data
    GROUP BY `Customer Status`;


